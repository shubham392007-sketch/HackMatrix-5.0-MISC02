    async def synthesize_mode_a_query_with_ollama(
        self,
        skills_data: Union[List[str], List[Dict[str, Any]]],
        location: Optional[str] = None,
        remote_only: bool = False,
    ) -> ModeASearchIntent:
        """
        Synthesizes structured security-focused search intent using local Ollama (qwen3:8b).
        Strictly prioritizes dominant specialist security competencies over general supporting tools.
        Returns: ModeASearchIntent
        """
        normalized_skills: List[Dict[str, Any]] = []
        for item in (skills_data or []):
            if isinstance(item, str):
                normalized_skills.append({
                    "name": item,
                    "proficiency": "Practitioner",
                    "verification_status": "verified",
                    "confidence": 0.88,
                })
            elif isinstance(item, dict):
                normalized_skills.append(item)

        if not normalized_skills:
            fallback = self._deterministic_security_fallback([])
            fallback.used_fallback = True
            return fallback

        fallback_intent = self._deterministic_security_fallback(normalized_skills)

        # Build compact structured profile for Ollama
        profile_lines = []
        for s in normalized_skills[:10]:
            name = s.get("name") or s.get("canonical_name") or s.get("id") or "Technical Skill"
            prof = s.get("proficiency") or "Practitioner"
            is_v = s.get("verification_status") in ("verified", "reviewed") or s.get("verified", False)
            conf = s.get("confidence") or 0.85
            conf_val = f"{conf:.2f}" if isinstance(conf, float) else f"{conf}%"
            ev = s.get("evidence_summary")
            line = f"- {name} (Proficiency: {prof}, Verified: {is_v}, Confidence: {conf_val})"
            if ev:
                line += f" [Evidence: {ev[:60]}]"
            profile_lines.append(line)

        profile_text = "\n".join(profile_lines)
        filter_text = f"Location: {location or 'Any'}, Remote Only: {remote_only}"

        prompt = (
            "Analyze the candidate's selected skills and generate structured job search intent.\n"
            "CRITICAL REQUIREMENTS:\n"
            "1. DOMINANT SPECIALIST DOMAIN: Specialized security, cryptography, and vulnerability skills MUST take precedence "
            "over general supporting software/devops skills (e.g. TypeScript, APIs, Cloud are supporting implementation tools, "
            "NOT the primary career domain; do NOT generate frontend/full-stack/devops roles when specialized security skills are present).\n"
            "2. REAL-LIFE MARKET REALISM & REACHABILITY: The generated role families MUST be realistic, reachable, and established "
            "in the actual job market. Do not generate only hyper-niche or theoretical job titles. Real employers hire under standard, "
            "high-volume titles such as 'Cybersecurity Engineer', 'Security Engineer', 'Application Security Engineer', "
            "'Information Security Engineer', 'Penetration Tester', etc. Roles must make sense in real life and represent practical, "
            "reachable openings for this candidate profile.\n\n"
            f"Selected Skills Profile:\n{profile_text}\n\n"
            f"Filters: {filter_text}\n\n"
            "Return ONLY a valid JSON object matching this schema:\n"
            "{\n"
            '  "primary_domain": "string (e.g. cybersecurity_and_application_security)",\n'
            '  "search_query": "consolidated provider-compatible search query (e.g. Cybersecurity Engineer OR Security Engineer OR Application Security)",\n'
            '  "role_families": ["Cybersecurity Engineer", "Security Engineer", "Application Security Engineer", "Offensive Security Engineer", "Information Security Specialist"],\n'
            '  "must_include": ["cybersecurity", "application security", "cryptography", "vulnerability"],\n'
            '  "supporting_terms": ["api security", "security automation", "cloud security"],\n'
            '  "exclude_terms": ["Frontend Engineer", "Full Stack Developer", "UI Designer"]\n'
            "}"
        )

        ollama_url = getattr(self.settings, "ollama_base_url", "http://localhost:11434").rstrip("/")
        model = getattr(self.settings, "ollama_qwen_model", "qwen3:8b")
        t0 = asyncio.get_event_loop().time()

        try:
            async with httpx.AsyncClient(timeout=3.5) as client:
                resp = await client.post(
                    f"{ollama_url}/api/chat",
                    json={
                        "model": model,
                        "think": False,
                        "keep_alive": "60m",
                        "format": "json",
                        "messages": [{"role": "user", "content": prompt}],
                        "stream": False,
                        "options": {
                            "temperature": 0.0,
                            "num_ctx": 1024,
                            "num_predict": 120,
                            "num_thread": 8,
                        },
                    },
                )
                latency = asyncio.get_event_loop().time() - t0

                if resp.status_code == 200:
                    data = resp.json()
                    msg_content = data.get("message", {}).get("content", "").strip()
                    if msg_content.startswith("```"):
                        msg_content = re.sub(r"^```(?:json)?\s*", "", msg_content)
                        msg_content = re.sub(r"\s*```$", "", msg_content)
                    parsed_json = json.loads(msg_content)

                    primary_domain = str(parsed_json.get("primary_domain") or "").strip()
                    search_query = str(parsed_json.get("search_query") or "").strip()
                    role_families = [str(r).strip() for r in parsed_json.get("role_families", []) if str(r).strip()]
                    must_include = [str(m).strip() for m in parsed_json.get("must_include", []) if str(m).strip()]
                    supporting_terms = [str(s).strip() for s in parsed_json.get("supporting_terms", []) if str(s).strip()]
                    exclude_terms = [str(e).strip() for e in parsed_json.get("exclude_terms", []) if str(e).strip()]

                    if primary_domain and role_families and search_query:
                        intent = ModeASearchIntent(
                            primary_domain=primary_domain,
                            search_query=search_query,
                            role_families=role_families[:5],
                            must_include=must_include[:5],
                            supporting_terms=supporting_terms[:5],
                            exclude_terms=exclude_terms[:4],
                            ollama_latency_ms=round(latency * 1000, 1),
                            used_fallback=False,
                        )
                        logger.info(f"Ollama synthesized search intent in {latency:.2f}s: domain='{primary_domain}', query='{search_query}'")
                        return intent
        except Exception as e:
            latency = asyncio.get_event_loop().time() - t0
            logger.warning(f"Ollama inference error after {latency:.2f}s ({e}); using deterministic security fallback.")

        fallback_intent.ollama_latency_ms = round((asyncio.get_event_loop().time() - t0) * 1000, 1)
        fallback_intent.used_fallback = True
        return fallback_intent

    def _rank_jobs_locally(
        self,
        jobs: List[JobSearchResult],
        intent: ModeASearchIntent,
        selected_skills: List[Dict[str, Any]],
    ) -> List[JobSearchResult]:
        """
        Ranks returned provider jobs locally based on alignment with:
        1. Target role families in title (+25 pts)
        2. Dominant security domain & cryptography terms (+15 pts)
        3. must_include terms (+8 pts each, up to +32 pts)
        4. supporting_terms (+3 pts each, up to +12 pts)
        5. User's selected skills matched (+5 pts each, up to +20 pts)
        6. Penalties for exclude_terms (-30 pts in title, -15 pts in description)
        """
        role_pats = [rf.lower() for rf in intent.role_families]
        must_pats = [m.lower() for m in intent.must_include]
        supp_pats = [s.lower() for s in intent.supporting_terms]
        excl_pats = [e.lower() for e in intent.exclude_terms]
        skill_names = [s.get("name", "").lower() for s in selected_skills if s.get("name")]

        scored_jobs = []
        for job in jobs:
            title_lower = (job.title or "").lower()
            desc_lower = (job.description or "").lower()
            full_text = f"{title_lower} {desc_lower}"

            score = 30.0  # Base neutral score
            reasons = []

            # 1. Target role families match in title
            title_matched = False
            for rf in role_pats:
                if rf in title_lower:
                    score += 25.0
                    reasons.append(f"Title aligns with target role: '{rf}'")
                    title_matched = True
                    break

            # Security keywords in title if no specific role family matched
            if not title_matched and any(kw in title_lower for kw in ["security", "cryptograph", "exploit", "cyber", "penetration", "red team", "vulnerability"]):
                score += 15.0
                reasons.append("Title contains core security keyword")

            # 2. Negative keyword penalty
            for excl in excl_pats:
                if excl in title_lower:
                    score -= 30.0
                    reasons.append(f"Penalty: Excluded domain term in title ('{excl}')")
                elif excl in desc_lower:
                    score -= 10.0

            # 3. must_include matches
            must_count = 0
            for m in must_pats:
                if m in full_text and must_count < 4:
                    score += 8.0
                    must_count += 1
                    reasons.append(f"Core domain match: '{m}'")

            # 4. supporting_terms matches
            supp_count = 0
            for st in supp_pats:
                if st in full_text and supp_count < 3:
                    score += 3.0
                    supp_count += 1
                    reasons.append(f"Supporting skill match: '{st}'")

            # 5. Direct selected skill matches
            skill_count = 0
            for sn in skill_names:
                if sn in full_text and skill_count < 4:
                    score += 5.0
                    skill_count += 1
                    reasons.append(f"Candidate skill demonstrated: '{sn}'")

            final_score = max(5.0, min(99.0, score))
            job.local_relevance_score = round(final_score, 1)
            job.relevance_reasons = reasons[:5]
            scored_jobs.append((final_score, job))

        # Sort descending by local relevance score
        scored_jobs.sort(key=lambda x: x[0], reverse=True)
        return [j for _, j in scored_jobs]

    def _generate_cache_key(
        self,
        mode: str,
        query: str,
        location: Optional[str],
        remote_only: bool,
        skill_snapshot: Optional[str] = None,
    ) -> str:
        norm = f"{mode.lower()}|{query.strip().lower()}|{(location or '').strip().lower()}|{remote_only}|{skill_snapshot or ''}"
        return hashlib.sha256(norm.encode("utf-8")).hexdigest()

